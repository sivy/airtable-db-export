    result = runner.invoke(
        cli,
        [
            "-c",
            str(config_path),
            "test-ctx",
            "--key",
            "backend",
            "--value",
            "sqlite",
        ],
    )
    assert "Context OK" in result.output
    assert "Context backend == sqlite OK" in result.output


